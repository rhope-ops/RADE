#!/usr/bin/env bash
# RADE project checks (run last by scripts/check.sh). Pass = exit 0.
# Lanes (.claude/skills/deliver/SKILL.md; the Administrator, 2026-11-16): no argument = the full lane, everything.
# --fast = the fast lane: the quick checks below always (each reads its whole file, so a changed file is checked in full,
# and the logo source is checked for stale output); the engine tests only when a file they read changed against the merge
# base with origin/main; the app canary (needs network access to github.com) only in the full lane.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
lane=full
case "${1:-}" in --fast) lane=fast ;; "") ;; *) echo "usage: scripts/check.local.sh [--fast]" >&2; exit 2 ;; esac
# changed PATTERN: true in the full lane, when the merge base is unknown, or when a changed file matches the pattern.
changed() {
  [ "$lane" = full ] && return 0
  local base files
  base="$(git merge-base HEAD origin/main 2>/dev/null)" || return 0
  files="$(git diff --name-only "$base"; git ls-files -o --exclude-standard)"
  grep -qE "$1" <<<"$files"   # no pipe: with pipefail, "| grep -q" on a long list can end in SIGPIPE and read as "not changed"
}
# Manifest contract: schemas/rade-manifest.schema.json plus cross-references (scripts/check_manifest.py).
python3 scripts/check_manifest.py
# Engine (moved from rhope-ops/90-161.Z, 2026-11-14): it compiles. Each app's own tests build and check its bundles.
python3 -m py_compile engine/rade_build.py
# Engine file list (apps lock these files; the release workflow signs the list): the trace runs and names the engine.
python3 scripts/engine_files.py | grep -q '  engine/rade_build.py$'
# RADE page (index.html): its application list is valid, and each entry names a repository and a manifest path.
python3 -c "import json,re; c=json.load(open('apps.json')); assert c['apps'] and all(re.fullmatch(r'[\w.-]+/[\w.-]+', a['repo']) and a['manifest'].endswith('.json') for a in c['apps']), 'apps.json'"
# Logo (generated by scripts/build_logo.py; never hand-edited): the SVG is what the script makes now. The PNGs come from
# a browser render (scripts/render_logo.js), which is not byte-stable, so they are not compared.
lt="$(mktemp -d)"; trap 'rm -rf "$lt"' EXIT; mkdir -p "$lt/scripts"; cp scripts/build_logo.py "$lt/scripts/"
python3 "$lt/scripts/build_logo.py" > /dev/null
cmp -s "$lt/assets/logo/logo-rho.svg" assets/logo/logo-rho.svg || { echo "FAIL assets/logo/logo-rho.svg is stale: run python3 scripts/build_logo.py, then node scripts/render_logo.js"; exit 1; }
# App canary (the Administrator, 2026-11-15): this engine and schema still build every real application in apps.json
# (a read-only copy of each app's main branch; needs network access to github.com). Its own test is offline.
python3 tests/check_apps_test.py
if [ "$lane" = full ]; then python3 scripts/check_apps.py; else echo "SKIP app canary (fast lane: the full lane runs it)"; fi
# Engine behavior (deploy v1): build the sample bundle and run it in pwsh text mode.
if changed '^(engine/|tests/|schemas/|assets/|docs/window-design\.md$|scripts/check_manifest\.py$|scripts/check\.local\.sh$)'; then
  bash tests/engine_test.sh
else
  echo "SKIP engine tests (fast lane: no file they read changed; the full lane runs them)"
fi
