#!/usr/bin/env bash
# RADE project checks (run last by scripts/check.sh). Pass = exit 0.
# Lanes (.claude/skills/deliver/SKILL.md; the Administrator, 2026-11-16): no argument = the full lane, everything.
# --fast = the fast lane: the quick checks below always (each reads its whole file, so a changed file is checked in full,
# and the logo source is checked for stale output); the engine tests only when a file they read changed against the merge
# base with origin/main; the app canary (needs network access to github.com) only in the full lane.
# RADE_OFFLINE=1 (fleet v2): a run with no network skips the app canary and the README apps part, each with a SKIP line.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
lane=full
case "${1:-}" in --fast) lane=fast ;; "") ;; *) echo "usage: scripts/check.local.sh [--fast]" >&2; exit 2 ;; esac
# changed PATTERN: true in the full lane, when the merge base is unknown, or when a changed file matches the pattern.
changed() {
  [ "$lane" = full ] && return 0
  local base files
  base="$(git merge-base HEAD origin/main 2>/dev/null)" || return 0
  files="$(git diff --name-only "$base"; git ls-files -o --exclude-standard)"
  grep -qE "$1" <<<"$files"   # no pipe: with pipefail, "| grep -q" on a long list can end in SIGPIPE and read as "not changed"
}
# Engine behavior (deploy v1) takes most of the time, so the engine tests start first, in the background, beside the
# checks below, and their result is read at the end (speed audit S4; the Administrator, 2026-11-18).
engine_files='^(engine/|tests/|schemas/|assets/|docs/window-design\.md$|scripts/check_manifest\.py$|scripts/check\.local\.sh$|scripts/lint\.sh$)'
# kt PID: stops a process and its child processes (children first), so no engine test runs on after the lane ends.
kt() { local c; for c in $(pgrep -P "$1" 2>/dev/null); do kt "$c"; done; kill "$1" 2>/dev/null || true; }
et=""; eo="$(mktemp)"; lt="$(mktemp -d)"; trap '[ -z "$et" ] || kt "$et"; rm -rf "$lt" "$eo"' EXIT
if changed "$engine_files"; then bash tests/engine_test.sh > "$eo" 2>&1 & et=$!; fi
# Manifest contract: schemas/rade-manifest.schema.json plus cross-references (scripts/check_manifest.py).
python3 scripts/check_manifest.py
# Code standard (the Administrator, 2026-11-17; docs/code-standard.md): the check proves itself, then measures every
# source file against the shrink-only baseline. Both lanes: it reads every file in about 1 s.
python3 scripts/code_standard.py --test
python3 scripts/code_standard.py
# Network rules of the checks (the Administrator, 2026-11-17): no Windows sign-in to a tested address; a Config
# address only on the app's own host. About 1 s.
tests/net_rules_test.sh
# No reconnaissance (AGENTS.md "Project rules"; the Administrator, 2026-11-18): no word that finds hosts, pings, tests a
# port or looks up a name in the engine sources or the sample app. A word search that proves itself first. Under 1 s.
python3 scripts/no_recon.py --test
python3 scripts/no_recon.py
# UI standard v1 (the Administrator, 2026-11-20; docs/ui-standard.md): every color pair meets its WCAG contrast, and the
# page's colors are the tokens'. Under 1 s.
python3 scripts/ui_tokens.py | tail -1
# The content hash of engine/rade_hash.py (UI standard v1 brief item 9): its unit test. Under 1 s.
python3 tests/rade_hash_test.py | tail -1
# Engine (moved from rhope-ops/90-161.Z, 2026-11-14): it compiles. Each app's own tests build and check its bundles.
python3 -m py_compile engine/rade_build.py
# Engine file list (apps lock these files; the release workflow signs the list): the trace runs and names the engine.
python3 scripts/engine_files.py | grep -q '  engine/rade_build.py$'
# RADE page (index.html): its application list is valid, and each entry names a repository and a manifest path.
python3 -c "import json,re; c=json.load(open('apps.json')); assert c['apps'] and all(re.fullmatch(r'[\w.-]+/[\w.-]+', a['repo']) and a['manifest'].endswith('.json') for a in c['apps']), 'apps.json'"
# RADE page security rules (fleet v2): no HTML sink, CSP script hash, no-referrer, new-tab links (tests/page_test.py).
python3 tests/page_test.py
# Logo (generated by scripts/build_logo.py; never hand-edited): the SVG is what the script makes now. The PNGs come from
# a browser render (scripts/render_logo.js), which is not byte-stable, so they are not compared.
mkdir -p "$lt/scripts"; cp scripts/build_logo.py "$lt/scripts/"
python3 "$lt/scripts/build_logo.py" > /dev/null
cmp -s "$lt/assets/logo/logo-rho.svg" assets/logo/logo-rho.svg || { echo "FAIL logo-rho.svg is stale: run python3 scripts/build_logo.py, then node scripts/render_logo.js logo-rho"; exit 1; }
# App canary (the Administrator, 2026-11-15): this engine and schema still build every real application in apps.json
# (a read-only copy of each app's main branch; needs network access to github.com). Its own test is offline.
python3 tests/check_apps_test.py
if [ "${RADE_OFFLINE:-}" = 1 ]; then echo "SKIP app canary (RADE_OFFLINE=1: no network; not a pass)"; elif [ "$lane" = full ]; then python3 scripts/check_apps.py; else echo "SKIP app canary (fast lane: the full lane runs it)"; fi
# README apps part (the Administrator, 2026-11-21): README.md shows each app's newest script as the RADE page does, written by
# scripts/build_readme.py --write; the check fails when it is old (needs network access to github.com). Its own test is offline.
python3 tests/build_readme_test.py
if [ "${RADE_OFFLINE:-}" = 1 ]; then echo "SKIP README apps part (RADE_OFFLINE=1: no network; not a pass)"; elif [ "$lane" = full ]; then python3 scripts/build_readme.py | tail -3 || exit 1; else echo "SKIP README apps part (fast lane: the full lane runs it)"; fi
# Engine behavior (deploy v1): the sample bundle built and run in pwsh text mode (started at the top), its layout and its lint.
if [ -n "$et" ]; then
  if wait "$et"; then et=""; cat "$eo"; else et=""; cat "$eo"; echo "FAIL engine tests (tests/engine_test.sh)"; exit 1; fi
  python3 tests/bundle_layout_test.py   # the Contents list and the shared blocks (docs/engine.md "Bundle layout")
  python3 tests/text_mode_51.py   # a text-mode run of the sample bundle (on Windows PowerShell 5.1 in the job text51 of window.yml)
  bash scripts/lint.sh   # PSScriptAnalyzer on the built sample bundle (apps lint their bundles with the same settings)
else
  echo "SKIP engine tests (fast lane: no file they read changed; the full lane runs them)"
fi
